// This program find product of two numbers;
#include <stdio.h>

int main() {
    int num1, num2;

    printf("Enter first number:");
    scanf("%d", &num1);
    printf("Enter second number:");
    scanf("%d", &num2);
    printf("The product of two input numbers is %d\n", num1*num2);
    
    return 0;
}